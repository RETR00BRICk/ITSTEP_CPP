#pragma once

#define MAX_NAME_LEN 30

/*
ООП - парадигма програмування, що будується на об'єктній декомпозиції.

Об'єктна декомпозиція вимагає виділення 
- сутностей предметної області програми
- характеристик цих сутностей
- поведінку цих сутностей

Головною метою ООП є абстракція. Абстракція дозволяє приховати зайву 
складність і зосередитись лише на суттєвих аспектах об’єкта, 
важливих у конкретному контексті.

Реалізація абстракції будується на трьох принципах:
1) Інкапсуляція
2) Наслідування
3) Поліморфізм

Інкапсуляція - принцип, який вимагає об'єднання даних та функцій, що з ними
працюють всередині класу, з розмежуванням на прихований внутрішній стан та публічний інтерфейс.

Клас - це креслення, яке визначає набір властивостей об'єктів та їх поведінку.
Об'єкт - конкретний екземпляр класу, що має власні значення властивостей (внутрішній стан).
*/

class Cat {
private: // специфікатори доступу
    char name[MAX_NAME_LEN]; // fields, поля, змінна-член класу
    int age = 0;
public:
    void printCat(); // методи, функція-член класу
    void askForFood();
    void makePurr();

    // Методи-аксесори
    // setter | модифікатор
    void setName(const char* newName);
    void setAge(int newAge);

    // getter | інспектор
    const char* getName() {
        return name;
    }
    int getAge() {
        return age;
    }
};
